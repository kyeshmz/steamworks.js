// Emits src/sdk/generated.rs: extern declarations, accessors, one function
// per flat API method, callback pointer-field copying and struct layouts.

import { NUM_INFO } from './model.mjs'

const RANGE = {
    bool: null,
    i8: ['-128', '127'], u8: ['0', '255'],
    i16: ['-32768', '32767'], u16: ['0', '65535'],
    i32: ['i32::MIN as i128', 'i32::MAX as i128'], u32: ['0', 'u32::MAX as i128'],
    i64: ['i64::MIN as i128', 'i64::MAX as i128'], u64: ['0', 'u64::MAX as i128'],
    isize: ['i64::MIN as i128', 'i64::MAX as i128'], usize: ['0', 'u64::MAX as i128'],
}
const RUST_NUM = { bool: 'bool', i8: 'i8', u8: 'u8', i16: 'i16', u16: 'u16', i32: 'i32', u32: 'u32', i64: 'i64', u64: 'u64', f32: 'f32', f64: 'f64', isize: 'isize', usize: 'usize' }

const PIPE = { user: 'Pipe::Client', gameserver: 'Pipe::Server', global: 'Pipe::Global' }

export function emitRust(model) {
    const out = []
    const { rustPath } = model
    out.push(`// @generated by scripts/sdk/generate.mjs from steam_api.json (${model.sdkVersion}).`)
    out.push('// Do not edit by hand: change the generator or scripts/sdk/overrides.mjs.')
    out.push('#![allow(non_snake_case, unused_mut, unused_variables, unused_unsafe, unused_imports, clippy::all)]')
    out.push('')
    out.push('use super::{extra, manual, Accessor, Args, Extra, MethodInfo, OutString, Pipe};')
    out.push('use super::{extra_cstr, js_bool, js_bytes, js_cstr, js_i64, js_num, js_struct, js_u64, js_undefined, pack, read_ptr, read_u32, unavailable, watch_call_result};')
    out.push('use napi::{Env, JsUnknown, Result};')
    out.push('use std::ffi::{c_char, c_void};')
    out.push('use std::mem::{offset_of, size_of};')
    out.push('use steamworks::sys;')
    out.push('')

    // --- extern declarations ------------------------------------------------
    const interfaces = model.interfaces.filter(i => !i.excluded)
    const ifaceIndex = new Map(interfaces.map((i, n) => [i.name, n]))
    const accessors = interfaces.flatMap(i => i.accessors.map(a => ({ ...a, iface: i.name })))
    out.push('extern "C" {')
    for (const a of accessors) out.push(`    fn ${a.flat}() -> *mut c_void;`)
    for (const m of model.methods) {
        if (m.status !== 'generated') continue
        const params = []
        if (!m.isStruct) params.push('self_: *mut c_void')
        m.params.forEach((p, i) => params.push(`p${i}: ${ffiType(p, rustPath)}`))
        const ret = ffiRet(m.ret, rustPath)
        out.push(`    fn ${m.flat}(${params.join(', ')})${ret ? ` -> ${ret}` : ''};`)
    }
    out.push('}')
    out.push('')

    // --- tables -----------------------------------------------------------------
    out.push(`pub static INTERFACE_NAMES: &[&str] = &[${interfaces.map(i => JSON.stringify(i.name)).join(', ')}];`)
    out.push('')
    out.push('pub static ACCESSORS: &[Accessor] = &[')
    for (const a of accessors) {
        out.push(`    Accessor { name: ${JSON.stringify(a.name)}, interface: ${ifaceIndex.get(a.iface)}, pipe: ${PIPE[a.kind]}, get: ${a.flat} },`)
    }
    out.push('];')
    out.push('')
    out.push('pub static METHODS: &[MethodInfo] = &[')
    for (const m of model.methods) {
        const iface = m.isStruct ? 'u16::MAX' : String(ifaceIndex.get(m.owner) ?? 'u16::MAX')
        out.push(`    MethodInfo { name: ${JSON.stringify(m.flat)}, interface: ${iface}, requires_steam: ${m.requiresSteam} },`)
    }
    out.push('];')
    out.push('')

    // --- dispatch -----------------------------------------------------------------
    out.push('pub unsafe fn call(env: &Env, method: u32, iface: *mut c_void, pipe: Pipe, a: &Args) -> Result<JsUnknown> {')
    out.push('    match method {')
    for (const m of model.methods) {
        if (m.status === 'generated') out.push(`        ${m.index} => m${m.index}(env, iface, pipe, a),`)
        else if (m.status === 'manual') out.push(`        ${m.index} => manual::${m.flat}(env, iface, pipe, a),`)
        else out.push(`        ${m.index} => Err(unavailable(${JSON.stringify(m.flat)}, ${JSON.stringify(m.reason ?? m.status)})),`)
    }
    out.push('        _ => Err(napi::Error::from_reason("unknown SDK method")),')
    out.push('    }')
    out.push('}')
    out.push('')

    for (const m of model.methods) {
        if (m.status !== 'generated') continue
        out.push(...emitMethod(m, rustPath))
        out.push('')
    }

    // --- callbacks: copy what pointer fields refer to -----------------------------
    out.push('pub unsafe fn callback_extras(id: i32, data: *const c_void, size: usize) -> Vec<Extra> {')
    out.push('    match id {')
    for (const cb of model.callbacks) {
        if (!cb.cstrFields.length) continue
        const path = rustPath(cb.name)
        if (cb.name === 'HTML_NeedsPaint_t') {
            out.push(`        ${cb.id} => {`)
            out.push(`            // pBGRA is unWide * unTall * 4 bytes of pixels, not a string.`)
            out.push(`            let w = read_u32(data, size, offset_of!(${path}, unWide)) as usize;`)
            out.push(`            let h = read_u32(data, size, offset_of!(${path}, unTall)) as usize;`)
            out.push(`            let p = read_ptr(data, size, offset_of!(${path}, pBGRA));`)
            out.push(`            let len = w.saturating_mul(h).saturating_mul(4).min(256 * 1024 * 1024);`)
            out.push(`            let pixels = if p.is_null() { Vec::new() } else { std::slice::from_raw_parts(p as *const u8, len).to_vec() };`)
            out.push(`            vec![Extra::Bytes(pixels)]`)
            out.push(`        }`)
            continue
        }
        const items = cb.cstrFields.map(f => `extra_cstr(read_ptr(data, size, ${offsetExpr(f, model)}))`)
        out.push(`        ${cb.id} => vec![${items.join(', ')}],`)
    }
    out.push('        _ => Vec::new(),')
    out.push('    }')
    out.push('}')
    out.push('')

    // --- layouts ----------------------------------------------------------------
    out.push('pub fn layouts() -> Vec<(&\'static str, usize, Vec<usize>)> {')
    out.push('    vec![')
    for (const r of model.records.values()) {
        if (r.opaque) continue
        const offsets = r.fields.map(f => offsetExpr(f, model))
        out.push(`        (${JSON.stringify(r.name)}, size_of::<${rustPath(r.rustName)}>(), vec![${offsets.join(', ')}]),`)
    }
    out.push('    ]')
    out.push('}')
    return out.join('\n') + '\n'
}

function offsetExpr(field, model) {
    // chain[i] is the record that contains path[i]
    return field.path.map((name, i) => `offset_of!(${model.rustPath(field.chain[i])}, ${name})`).join(' + ')
}

function ffiType(p, rustPath) {
    switch (p.kind) {
        case 'scalar': return RUST_NUM[p.num]
        case 'cstr': return '*const c_char'
        case 'structValue': return rustPath(p.record)
        default: return '*mut c_void'
    }
}

function ffiRet(r, rustPath) {
    switch (r.kind) {
        case 'void': return null
        case 'scalar': return RUST_NUM[r.num]
        case 'callResult': return 'u64'
        case 'cstr': return '*const c_char'
        case 'structValue': return rustPath(r.record)
        case 'structCopy':
        case 'bytes': return '*const c_void'
        default: throw new Error(`no FFI type for return kind ${r.kind}`)
    }
}

function toJs(num, expr) {
    if (num === 'bool') return `js_bool(env, ${expr})?`
    if (num === 'u64' || num === 'usize') return `js_u64(env, ${expr} as u64)?`
    if (num === 'i64' || num === 'isize') return `js_i64(env, ${expr} as i64)?`
    return `js_num(env, ${expr} as f64)?`
}

function decodeScalar(p, i) {
    const name = JSON.stringify(p.name)
    if (p.num === 'bool') return `a.bool(${i}, ${name})?`
    if (p.num === 'f32') return `a.float(${i}, ${name})? as f32`
    if (p.num === 'f64') return `a.float(${i}, ${name})?`
    // C enums carry any 32-bit value (flags are OR-ed together).
    const [lo, hi] = p.enumName ? ['i32::MIN as i128', 'u32::MAX as i128'] : RANGE[p.num]
    return `a.int(${i}, ${name}, ${lo}, ${hi})? as ${RUST_NUM[p.num]}`
}

function zero(num) {
    if (num === 'bool') return 'false'
    if (num === 'f32' || num === 'f64') return '0.0'
    return '0'
}

/** Rust expression (i128) for an element count or byte capacity. */
function countExpr(c) {
    if (c.from === 'fixed' || c.from === 'const') return `${c.value}i128`
    return `p${c.index} as i128`
}

function emitMethod(m, rustPath) {
    const lines = []
    lines.push(`// ${m.flat}`)
    lines.push(`unsafe fn m${m.index}(env: &Env, iface: *mut c_void, pipe: Pipe, a: &Args) -> Result<JsUnknown> {`)
    const args = []
    // pass 1: values that other parameters may refer to
    m.params.forEach((p, i) => {
        switch (p.kind) {
            case 'scalar':
                lines.push(`    let p${i} = ${decodeScalar(p, i)};`)
                args[i] = `p${i}`
                break
            case 'cstr':
                if (p.nullable) {
                    lines.push(`    let p${i} = a.cstr_opt(${i}, ${JSON.stringify(p.name)})?;`)
                    args[i] = `p${i}.as_ref().map_or(std::ptr::null(), |s| s.as_ptr())`
                } else {
                    lines.push(`    let p${i} = a.cstr(${i}, ${JSON.stringify(p.name)})?;`)
                    args[i] = `p${i}.as_ptr()`
                }
                break
            case 'out':
                lines.push(`    let mut p${i}: ${RUST_NUM[p.num]} = ${zero(p.num)};`)
                args[i] = `&mut p${i} as *mut ${RUST_NUM[p.num]} as *mut c_void`
                break
            case 'inout':
                lines.push(`    let mut p${i}: ${RUST_NUM[p.num]} = ${decodeScalar(p, i)};`)
                args[i] = `&mut p${i} as *mut ${RUST_NUM[p.num]} as *mut c_void`
                break
            case 'outCStrPtr':
                lines.push(`    let mut p${i}: *mut c_char = std::ptr::null_mut();`)
                args[i] = `&mut p${i} as *mut *mut c_char as *mut c_void`
                break
            case 'structValue':
                lines.push(`    let p${i}: ${rustPath(p.record)} = a.struct_val(${i}, ${JSON.stringify(p.name)})?;`)
                args[i] = `p${i}`
                break
            case 'strArray':
                lines.push(`    let mut p${i} = a.str_array(${i}, ${JSON.stringify(p.name)})?;`)
                args[i] = `p${i}.as_mut().map_or(std::ptr::null_mut(), |s| &mut s.raw as *mut sys::SteamParamStringArray_t as *mut c_void)`
                break
            case 'cstrList':
                lines.push(`    let mut p${i} = a.cstr_list(${i}, ${JSON.stringify(p.name)})?;`)
                args[i] = `p${i}.as_mut().map_or(std::ptr::null_mut(), |l| l.pointers.as_mut_ptr() as *mut c_void)`
                break
            case 'nullOnly':
                args[i] = 'std::ptr::null_mut()'
                break
        }
    })
    // pass 2: memory whose size depends on pass-1 values
    m.params.forEach((p, i) => {
        const name = JSON.stringify(p.name)
        switch (p.kind) {
            case 'mem': {
                const elem = p.bytes ? 1 : NUM_INFO[p.elem].size
                const min = elem === 1 ? countExpr(p.count) : `(${countExpr(p.count)}) * ${elem}`
                lines.push(`    let p${i} = a.mem(${i}, ${name}, ${min}, ${p.nullable})?;`)
                args[i] = `p${i}`
                break
            }
            case 'struct':
                lines.push(`    let p${i} = a.mem(${i}, ${name}, size_of::<${rustPath(p.record)}>() as i128, ${!!p.nullable})?;`)
                args[i] = `p${i}`
                break
            case 'structArray':
                lines.push(`    let p${i} = a.mem(${i}, ${name}, (${countExpr(p.count)}) * size_of::<${rustPath(p.record)}>() as i128, ${p.nullable})?;`)
                args[i] = `p${i}`
                break
            case 'outString':
                lines.push(`    let mut p${i} = OutString::new(${countExpr(p.cap)}, ${name}, a.method())?;`)
                args[i] = `p${i}.ptr()`
                break
        }
    })
    // out strings are returned in parameter order with the other outputs
    const outList = []
    m.params.forEach((p, i) => {
        if (p.kind === 'out' || p.kind === 'inout') outList.push(toJs(p.num, `p${i}`))
        if (p.kind === 'outCStrPtr') outList.push(`js_cstr(env, p${i})?`)
        if (p.kind === 'outString') outList.push(`p${i}.to_js(env)?`)
    })
    const callArgs = (m.isStruct ? [] : ['iface']).concat(args)
    const call = `${m.flat}(${callArgs.join(', ')})`
    let ret
    switch (m.ret.kind) {
        case 'void':
            lines.push(`    ${call};`)
            ret = null
            break
        case 'scalar':
            lines.push(`    let r = ${call};`)
            ret = toJs(m.ret.num, 'r')
            break
        case 'callResult':
            lines.push(`    let r = ${call};`)
            lines.push('    watch_call_result(pipe, r);')
            ret = 'js_u64(env, r)?'
            break
        case 'cstr':
            lines.push(`    let r = ${call};`)
            ret = 'js_cstr(env, r)?'
            break
        case 'structValue':
            lines.push(`    let r = ${call};`)
            ret = 'js_struct(env, &r)?'
            break
        case 'structCopy':
            lines.push(`    let r = ${call};`)
            ret = `js_bytes(env, r, size_of::<${rustPath(m.ret.record)}>())?`
            break
        case 'bytes':
            lines.push(`    let r = ${call};`)
            ret = `js_bytes(env, r, p${m.ret.lenIndex}.max(0) as usize)?`
            break
    }
    if (outList.length) {
        const values = ret ? [ret, ...outList] : outList
        lines.push(`    pack(env, vec![${values.join(', ')}])`)
    } else {
        lines.push(`    ${ret ? `Ok(${ret})` : 'js_undefined(env)'}`)
    }
    lines.push('}')
    return lines
}
