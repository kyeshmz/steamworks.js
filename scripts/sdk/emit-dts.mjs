// Emits lib/sdk/index.d.ts: TypeScript declarations with documentation for every
// interface accessor, method, struct, callback, enum and constant.

import {
    VALVE, cppSignature, docLocation, jsdoc, jsdocText, MANUAL_TS, pageForLocation, paramNote,
    tsParams, tsRecord, tsResult, valveMethodUrl,
} from './common.mjs'

const FIELD_TS = {
    bool: 'boolean', i8: 'number', u8: 'number', i16: 'number', u16: 'number', i32: 'number', u32: 'number',
    i64: 'bigint', u64: 'bigint', f32: 'number', f64: 'number', isize: 'bigint', usize: 'bigint', pointer: 'bigint',
}

export function emitDts(model, inputs) {
    const docs = inputs.docs
    const out = []
    const enumNames = new Set(model.enums.map(e => e.name))
    out.push(`// @generated by scripts/sdk/generate.mjs from steam_api.json (${model.sdkVersion}).`)
    out.push('// Do not edit by hand. Descriptions are from the comments in the Steamworks SDK')
    out.push('// headers, Copyright Valve Corporation; see docs/sdk/README.md.')
    out.push('/// <reference types="node" />')
    out.push('')
    out.push(...RUNTIME_TYPES(model))
    out.push('')

    // enums ------------------------------------------------------------------
    for (const e of model.enums) {
        const page = pageForLocation(docLocation(docs, 'enums', e.name), docs)
        out.push(...jsdoc([e.doc && jsdocText(e.doc), e.doc ? '' : null, `@see ${VALVE}/${page}#${e.name}`]))
        out.push(`export declare enum ${e.name} {`)
        for (const v of e.values) {
            out.push(...jsdoc([v.doc && jsdocText(v.doc)], '    '))
            out.push(`    ${v.name} = ${v.value},`)
        }
        out.push('}')
        out.push('')
    }

    // constants ----------------------------------------------------------------
    for (const c of model.consts) {
        out.push(...jsdoc([c.doc && jsdocText(c.doc), `C++: \`${c.type} ${c.name}\``]))
        const big = c.num === 'u64' || c.num === 'i64'
        out.push(`export declare const ${c.name}: ${big ? 'bigint' : 'number'}`)
    }
    out.push('')

    // structs --------------------------------------------------------------------
    for (const r of model.records.values()) {
        if (r.opaque) continue
        const page = pageForLocation(docLocation(docs, 'structs', r.rustName), docs)
        const head = [r.doc && jsdocText(r.doc)]
        if (r.callbackId !== null) head.push('', `Callback id ${r.callbackId}. Listen with \`on('${r.name}', handler)\`.`)
        if (r.name === r.rustName && !r.name.includes('__bindgen')) head.push(`@see ${VALVE}/${page}#${r.name}`)
        out.push(...jsdoc(head))
        out.push(`export declare class ${r.name} extends SteamStruct {`)
        for (const f of r.fields) {
            const type = fieldType(model, f, r, enumNames)
            if (!type) continue
            out.push(...jsdoc([f.doc && jsdocText(f.doc)], '    '))
            const readonly = ['struct', 'structArray', 'cstr', 'pointer'].includes(f.kind.k) ? 'readonly ' : ''
            out.push(`    ${readonly}${f.name}: ${type}`)
        }
        for (const m of r.methods) out.push(...methodDecl(model, m, '    '))
        if (r.name === 'SteamNetworkingMessage_t') {
            out.push('    /** Copy of the payload, present on messages returned by the Receive* calls. */')
            out.push('    data?: Buffer')
        }
        out.push('}')
        out.push('')
    }

    // callbacks map ---------------------------------------------------------------
    out.push('/** Every callback struct, keyed by its SDK name. */')
    out.push('export interface SteamCallbacks {')
    for (const cb of model.callbacks) {
        if (cb.record.opaque) continue
        out.push(`    ${cb.name}: ${cb.record.name}`)
    }
    out.push('}')
    out.push('')

    // interfaces ------------------------------------------------------------------
    for (const iface of model.interfaces) {
        if (iface.excluded) continue
        const head = [iface.doc && jsdocText(iface.doc), iface.doc ? '' : null]
        if (iface.pending) head.push(`**Not available yet:** ${iface.pending}`, '')
        head.push(`@see ${VALVE}/${iface.name}`)
        out.push(...jsdoc(head))
        out.push(`export interface ${iface.name} {`)
        for (const m of iface.methods) out.push(...methodDecl(model, m, '    '))
        out.push('}')
        out.push('')
        for (const a of iface.accessors) {
            const note = a.kind === 'gameserver'
                ? `The game server's ${iface.name} (\`${a.name}()\` in C++). Requires \`initGameServer()\`.`
                : `\`${a.name}()\` in C++. Requires \`init()\`${a.kind === 'global' ? ' or `initGameServer()`' : ''}.`
            out.push(...jsdoc([note, `@see ${VALVE}/${iface.name}`]))
            out.push(`export declare const ${a.name}: ${iface.name}`)
        }
        out.push('')
    }
    return out.join('\n') + '\n'
}

function fieldType(model, f, r, enumNames) {
    const k = f.kind
    switch (k.k) {
        case 'string': return 'string'
        case 'bytes': return 'Uint8Array'
        case 'array': return `${k.enumName && enumNames.has(k.enumName) ? k.enumName : FIELD_TS[k.of]}[]`
        case 'struct': return tsRecord(model, k.name)
        case 'structArray': return `${tsRecord(model, k.name)}[]`
        case 'cstr': return r.callbackId !== null ? 'string | null' : 'bigint'
        case 'opaque': return null
        default:
            if (k.enumName && enumNames.has(k.enumName)) return k.enumName
            return FIELD_TS[k.k] ?? 'unknown'
    }
}

function methodDecl(model, m, indent) {
    if (m.status === 'excluded') return []
    const lines = []
    const doc = []
    if (m.doc) doc.push(jsdocText(m.doc), '')
    if (m.status === 'manual') doc.push(`Hand-written binding: ${m.reason}`, '')
    if (m.status === 'unsupported' || m.status === 'pending') doc.push(`**Not available from JavaScript:** ${m.reason}`, '')
    if (/DEPRECATED/i.test(m.doc ?? '') || /_DEPRECATED$|_Legacy$/.test(m.jsName)) doc.push('@deprecated Deprecated by Valve.')
    const shown = m.params.filter(p => !p.isSelf)
    for (const p of shown) {
        const note = paramNote(model, p, m)
        doc.push(`@param ${p.name} \`${p.cType}\`${note ? `. ${note}` : ''}`)
    }
    if (m.callresult) doc.push(`@returns A Promise of the \`${m.callresult}\` call result (rejects if Steam returns k_uAPICallInvalid or an I/O failure).`)
    if (m.callback) doc.push(`Steam posts \`${m.callback}\` when done; listen with \`on('${m.callback}', ...)\`.`)
    doc.push(`C++: \`${cppSignature(m)}\``)
    if (!m.isStruct) doc.push(`@see ${valveMethodUrl(m)}`)
    lines.push(...jsdoc(doc, indent))
    if (m.status === 'manual') {
        const t = MANUAL_TS[m.flat]
        lines.push(`${indent}${m.jsName}(${t.params}): ${t.ret}`)
    } else if (m.status !== 'generated') {
        lines.push(`${indent}${m.jsName}(...args: never[]): never`)
    } else {
        lines.push(`${indent}${m.jsName}(${tsParams(model, m)}): ${tsResult(model, m)}`)
    }
    return lines
}

