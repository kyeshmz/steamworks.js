// Emits the Markdown API reference under docs/sdk/.

import {
    VALVE, cppSignature, docLocation, MANUAL_TS, pageForLocation, paramNote, tsParams, tsRecord,
    tsResult, valveMethodUrl,
} from './common.mjs'

const STATUS_LABEL = {
    generated: 'Generated',
    manual: 'Hand-written',
    unsupported: 'Not available',
    pending: 'Not implemented yet',
    excluded: 'Not exposed',
}

/** Valve comment text as a Markdown blockquote. */
function quote(text) {
    return text.split('\n').map(l => `> ${l.replace(/</g, '&lt;')}`.trimEnd()).join('\n')
}

function anchor(name) {
    return name.toLowerCase().replace(/[^a-z0-9_-]/g, '')
}

export function emitDocs(model, inputs) {
    const docs = inputs.docs
    const files = {}
    const group = docs.diagnostics?.groupMembers ?? {}
    const byFlat = new Map(model.methods.map(m => [m.flat, m]))
    const header = (title) => [
        `<!-- @generated by scripts/sdk/generate.mjs from steam_api.json (${model.sdkVersion}). Do not edit. -->`,
        '',
        `# ${title}`,
        '',
    ]

    // ---- index ---------------------------------------------------------------
    const index = header('Steamworks SDK reference (1:1 layer)')
    index.push(
        'Every interface, method, struct, callback, enum and constant in the Steamworks SDK\'s',
        '`steam_api.json`, as exposed by `require(\'@kyeshmz/steamworks.js\').sdk`. Names match the',
        'C++ SDK: accessors are the C++ accessor functions (`SteamUserStats()` becomes',
        '`sdk.SteamUserStats`), methods use their flat API names (overloads get their',
        '`STEAM_FLAT_NAME`, e.g. `GetStatInt32`), and struct fields keep their C++ names.',
        '',
        'Read [the guide](../guide/sdk.md) first: it explains how parameters, outputs, buffers,',
        'call results and callbacks map to JavaScript. Every page here is generated from the SDK',
        'that this package links against, so it cannot drift from the binary.',
        '',
        '| Interface | Accessors | Methods | Available |',
        '|---|---|---|---|',
    )
    for (const iface of model.interfaces) {
        const total = iface.methods.length
        const ok = iface.methods.filter(m => m.status === 'generated' || m.status === 'manual').length
        const accessors = iface.accessors.map(a => `\`${a.name}\``).join(', ') || '—'
        const name = iface.excluded ? iface.name : `[${iface.name}](interfaces/${iface.name}.md)`
        index.push(`| ${name} | ${accessors} | ${total} | ${iface.excluded ? 'not exposed' : `${ok}/${total}`} |`)
    }
    const counts = {}
    for (const m of model.methods) counts[m.status] = (counts[m.status] ?? 0) + 1
    index.push(
        '',
        `Totals across interfaces and struct methods: ${model.methods.length} methods; ` +
        Object.entries(counts).map(([k, v]) => `${v} ${STATUS_LABEL[k].toLowerCase()}`).join(', ') + '.',
        'See [coverage](coverage.md) for every method that is not generated and why.',
        '',
        '- [Callbacks](callbacks.md): every callback and call result struct, with its id',
        '- [Structs](structs.md): data structures and their methods',
        '- [Enums](enums.md)',
        '- [Constants](constants.md)',
        '',
        '## Source and attribution',
        '',
        `Generated from \`steam_api.json\` and the headers of the Steamworks SDK shipped with`,
        `steamworks-sys (\`${model.sdkVersion}\`). Quoted descriptions are the comments in those`,
        'headers, Copyright Valve Corporation, reproduced to document the interfaces they describe.',
        `Valve's own documentation is linked from every entry and is the authority: <${VALVE}>.`,
    )
    files['docs/sdk/README.md'] = index.join('\n') + '\n'

    // ---- interfaces ------------------------------------------------------------
    for (const iface of model.interfaces) {
        if (iface.excluded) continue
        const page = header(iface.name)
        if (iface.doc) page.push(quote(iface.doc), '')
        page.push(`Valve documentation: <${VALVE}/${iface.name}>`, '')
        page.push('| Accessor | C++ | Needs |', '|---|---|---|')
        for (const a of iface.accessors) {
            const needs = a.kind === 'gameserver' ? '`initGameServer()`' : a.kind === 'global' ? '`init()` or `initGameServer()`' : '`init()`'
            page.push(`| \`sdk.${a.name}\` | \`${a.name}()\` | ${needs} |`)
        }
        page.push('')
        if (iface.pending) page.push(`**Not implemented yet:** ${iface.pending}`, '')
        page.push('## Methods', '')
        page.push('| Method | Returns | Status |', '|---|---|---|')
        for (const m of iface.methods) {
            const ret = m.status === 'generated' ? `\`${tsResult(model, m).replace(/\|/g, '\\|')}\`` : m.status === 'manual' ? `\`${MANUAL_TS[m.flat].ret.replace(/\|/g, '\\|')}\`` : '—'
            page.push(`| [${m.jsName}](#${anchor(m.jsName)}) | ${ret} | ${STATUS_LABEL[m.status]} |`)
        }
        page.push('')
        const accessor = iface.accessors[0]?.name ?? iface.name
        for (const m of iface.methods) page.push(...methodSection(model, m, accessor, group, byFlat))
        files[`docs/sdk/interfaces/${iface.name}.md`] = page.join('\n') + '\n'
    }

    // ---- callbacks -----------------------------------------------------------------
    const cbPage = header('Callbacks and call results')
    cbPage.push(
        'Subscribe with `sdk.on(name, handler)`; call results are returned as Promises by the',
        'method that starts them. The handler receives an instance of the struct below; fields',
        'are read from the struct\'s bytes when accessed. See [the guide](../guide/sdk.md#callbacks).',
        '',
        '| Callback | Id | Delivered as |', '|---|---|---|',
    )
    const callResultOf = new Map()
    for (const m of model.methods) if (m.callresult) {
        if (!callResultOf.has(m.callresult)) callResultOf.set(m.callresult, [])
        callResultOf.get(m.callresult).push(m)
    }
    const callbackOf = new Map()
    for (const m of model.methods) if (m.callback) {
        if (!callbackOf.has(m.callback)) callbackOf.set(m.callback, [])
        callbackOf.get(m.callback).push(m)
    }
    for (const cb of model.callbacks) {
        const as = callResultOf.has(cb.name) ? 'call result' : 'callback'
        cbPage.push(`| [${cb.name}](#${anchor(cb.name)}) | ${cb.id} | ${as} |`)
    }
    cbPage.push('')
    for (const cb of model.callbacks) {
        const r = cb.record
        const pageName = pageForLocation(docLocation(docs, 'structs', cb.name), docs)
        cbPage.push(`## ${cb.name}`, '')
        cbPage.push(`Id \`${cb.id}\` · <${VALVE}/${pageName}#${cb.name}>`, '')
        if (cb.doc) cbPage.push(quote(cb.doc), '')
        const results = callResultOf.get(cb.name)
        if (results) cbPage.push(`Call result of: ${results.map(m => `\`${m.owner}.${m.jsName}\``).join(', ')}.`, '')
        const posted = callbackOf.get(cb.name)
        if (posted) cbPage.push(`Posted after: ${posted.map(m => `\`${m.owner}.${m.jsName}\``).join(', ')}.`, '')
        const shared = model.callbacksById.get(cb.id).filter(o => o !== cb)
        if (shared.length) cbPage.push(`The SDK uses id ${cb.id} for ${shared.map(o => `\`${o.name}\``).join(', ')} too; handlers for every struct with this id are called.`, '')
        cbPage.push(...fieldTable(model, r))
    }
    files['docs/sdk/callbacks.md'] = cbPage.join('\n') + '\n'

    // ---- structs --------------------------------------------------------------------
    const stPage = header('Structs')
    stPage.push(
        'Structs are classes over the struct\'s bytes (`new sdk.SteamNetworkingIdentity()`).',
        'Fields read and write those bytes using the layout of the current platform; struct',
        'methods call the SDK\'s flat struct functions. Pass an instance wherever the SDK takes',
        'a pointer or reference to the struct.',
        '',
    )
    for (const r of model.records.values()) {
        if (r.opaque || r.callbackId !== null) continue
        stPage.push(`## ${r.name}`, '')
        if (r.name === r.rustName) stPage.push(`<${VALVE}/${pageForLocation(docLocation(docs, 'structs', r.rustName), docs)}#${r.name}>`, '')
        if (r.doc) stPage.push(quote(r.doc), '')
        stPage.push(...fieldTable(model, r))
        if (r.methods.length) {
            stPage.push('**Methods**', '', '| Method | Signature | Status |', '|---|---|---|')
            for (const m of r.methods) {
                const sig = m.status === 'generated' ? `\`${m.jsName}(${tsParams(model, m)}): ${tsResult(model, m)}\``.replace(/\|/g, '\\|') : '—'
                const note = m.status === 'generated' ? (m.doc ? m.doc.split('\n')[0] : '') : m.reason
                stPage.push(`| \`${m.jsName}\` | ${sig} | ${STATUS_LABEL[m.status]}${note ? `: ${note.replace(/\|/g, '\\|')}` : ''} |`)
            }
            stPage.push('')
        }
    }
    files['docs/sdk/structs.md'] = stPage.join('\n') + '\n'

    // ---- enums --------------------------------------------------------------------------
    const enPage = header('Enums')
    enPage.push('Enums are exported as objects mapping names to values and values to names, like TypeScript numeric enums (`sdk.EResult.k_EResultOK === 1`).', '')
    for (const e of model.enums) {
        enPage.push(`## ${e.name}`, '')
        enPage.push(`<${VALVE}/${pageForLocation(docLocation(docs, 'enums', e.name), docs)}#${e.name}>`, '')
        if (e.doc) enPage.push(quote(e.doc), '')
        enPage.push('| Name | Value | Description |', '|---|---|---|')
        for (const v of e.values) enPage.push(`| \`${v.name}\` | ${v.value} | ${(v.doc ?? '').replace(/\n/g, ' ').replace(/\|/g, '\\|')} |`)
        enPage.push('')
    }
    files['docs/sdk/enums.md'] = enPage.join('\n') + '\n'

    // ---- constants ------------------------------------------------------------------------
    const cPage = header('Constants')
    cPage.push('Exported on `sdk` with their C++ names. 64-bit constants are bigints.', '', '| Name | C++ type | Value | Description |', '|---|---|---|---|')
    for (const c of model.consts) {
        const big = c.num === 'u64' || c.num === 'i64'
        let v = c.value
        if (big) v = `${BigInt.asUintN(64, BigInt(v))}n`
        cPage.push(`| \`${c.name}\` | \`${c.type}\` | ${v} | ${(c.doc ?? '').replace(/\n/g, ' ').replace(/\|/g, '\\|')} |`)
    }
    files['docs/sdk/constants.md'] = cPage.join('\n') + '\n'

    // ---- coverage ---------------------------------------------------------------------------
    const cov = header('Coverage')
    cov.push(
        `This layer covers ${model.methods.length} flat API methods (interface and struct methods) from \`${model.sdkVersion}\`.`,
        '',
        '| Status | Methods | Meaning |', '|---|---|---|',
        `| Generated | ${counts.generated ?? 0} | Bound mechanically from steam_api.json and the bindgen types. |`,
        `| Hand-written | ${counts.manual ?? 0} | Bound in \`src/sdk/manual.rs\` because the parameters need custom marshalling. |`,
        `| Not implemented yet | ${counts.pending ?? 0} | Expressible, but not written yet. |`,
        `| Not available | ${counts.unsupported ?? 0} | Cannot be called safely from JavaScript, or the type is not in the public SDK. |`,
        `| Not exposed | ${counts.excluded ?? 0} | Interfaces that only exist to be implemented by C++ code, or plumbing init() already handles. |`,
        '',
        'Calling a method that is not available throws a `SteamSdkError` with the reason below.',
        '',
    )
    for (const status of ['manual', 'pending', 'unsupported']) {
        const list = model.methods.filter(m => m.status === status)
        if (!list.length) continue
        cov.push(`## ${STATUS_LABEL[status]}`, '', '| Method | Reason |', '|---|---|')
        for (const m of list) cov.push(`| \`${m.owner}.${m.jsName}\` | ${(m.reason ?? '').replace(/\|/g, '\\|')} |`)
        cov.push('')
    }
    cov.push('## Not exposed', '', '| Interface | Reason |', '|---|---|')
    for (const iface of model.interfaces.filter(i => i.excluded)) cov.push(`| \`${iface.name}\` | ${iface.excluded} |`)
    cov.push('')
    files['docs/sdk/coverage.md'] = cov.join('\n') + '\n'
    return files
}

function fieldTable(model, r) {
    if (!r.fields.length) return ['No fields.', '']
    const lines = ['| Field | Type | Description |', '|---|---|---|']
    for (const f of r.fields) {
        if (f.kind.k === 'opaque') continue
        lines.push(`| \`${f.name}\` | ${fieldTs(model, f)} | ${(f.doc ?? '').replace(/\n/g, ' ').replace(/\|/g, '\\|')} |`)
    }
    lines.push('')
    return lines
}

function fieldTs(model, f) {
    const k = f.kind
    const scalar = { bool: 'boolean', pointer: 'bigint (address)' }
    switch (k.k) {
        case 'string': return `string (char[${k.len}])`
        case 'bytes': return `Uint8Array (${k.len} bytes)`
        case 'array': return `${k.enumName ?? k.of}[${k.len}]`
        case 'struct': return `[${tsRecord(model, k.name)}](structs.md#${anchor(tsRecord(model, k.name))})`
        case 'structArray': return `${tsRecord(model, k.name)}[${k.len}]`
        case 'cstr': return 'string \\| null'
        default: return k.enumName ? `[${k.enumName}](enums.md#${anchor(k.enumName)})` : scalar[k.k] ?? (k.k.endsWith('64') || k.k.endsWith('size') ? 'bigint' : 'number')
    }
}

function methodSection(model, m, accessor, group, byFlat) {
    const lines = [`### ${m.jsName}`, '']
    if (m.status !== 'generated' && m.status !== 'manual') {
        lines.push(`**${STATUS_LABEL[m.status]}:** ${m.reason}`, '')
    }
    if (m.status === 'generated') {
        lines.push('```ts', `sdk.${accessor}.${m.jsName}(${tsParams(model, m)}): ${tsResult(model, m)}`, '```', '')
    } else if (m.status === 'manual') {
        const t = MANUAL_TS[m.flat]
        lines.push('```ts', `sdk.${accessor}.${m.jsName}(${t.params}): ${t.ret}`, '```', '', `Hand-written binding: ${m.reason}`, '')
    }
    lines.push('```cpp', cppSignature(m), '```', '')
    if (m.doc) lines.push(quote(m.doc), '')
    else if (group[m.flat] && byFlat.get(group[m.flat])) {
        const leader = byFlat.get(group[m.flat])
        lines.push(`Documented together with [${leader.jsName}](#${anchor(leader.jsName)}) in the SDK header.`, '')
    }
    const params = m.params.filter(p => !p.isSelf)
    if (params.length && m.status !== 'excluded') {
        lines.push('| Parameter | C++ type | Notes |', '|---|---|---|')
        for (const p of params) lines.push(`| \`${p.name}\` | \`${p.cType}\` | ${paramNote(model, p, m).replace(/\|/g, '\\|')} |`)
        lines.push('')
    }
    if (m.callresult) lines.push(`Returns a Promise of [\`${m.callresult}\`](../callbacks.md#${anchor(m.callresult)}).`, '')
    if (m.callback) lines.push(`Steam posts [\`${m.callback}\`](../callbacks.md#${anchor(m.callback)}) when done.`, '')
    lines.push(`Valve: <${valveMethodUrl(m)}>`, '')
    return lines
}
