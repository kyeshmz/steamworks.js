// Emits lib/sdk/generated.js: the tables lib/sdk/runtime.js turns into the
// JavaScript API (namespaces, struct classes, enums, constants, callbacks).
//
// Parameter specs, one per C parameter, in C order:
//   ['s', name]                             scalar (validated natively)
//   ['c', name, nullable]                   const char *
//   ['m', name, dir, elem, count, nullable, bytes]   TypedArray / Buffer
//   ['t', name, dir, record, nullable]      one struct
//   ['ta', name, dir, record, count, nullable]       struct array
//   ['tv', name, record]                    struct by value
//   ['sa', name]  ['cl', name]              string[] marshalled natively
//   ['o', name]  ['io', name]  ['os', name]  ['op', name]   outputs returned natively
//   ['n', name]                             always NULL
// count: ['p', paramIndex] | ['i', inoutParamIndex] | ['k', constant]
// Return specs: ['v'] ['s'] ['c'] ['cr', record] ['tv', record] ['tc', record] ['b']

const KIND = {
    scalar: 's', cstr: 'c', mem: 'm', struct: 't', structArray: 'ta', structValue: 'tv',
    strArray: 'sa', cstrList: 'cl', out: 'o', inout: 'io', outString: 'os', outCStrPtr: 'op', nullOnly: 'n',
}

export function emitJs(model) {
    const recName = (rust) => model.records.get(rust)?.name ?? rust
    const count = (c) => {
        if (!c) return null
        if (c.from === 'param') return ['p', c.index]
        if (c.from === 'inout') return ['i', c.index]
        return ['k', c.value]
    }
    const paramSpec = (p) => {
        const k = KIND[p.kind]
        const name = p.isSelf ? 'self' : p.key
        switch (p.kind) {
            case 'cstr': return [k, name, !!p.nullable]
            case 'mem': return [k, name, p.dir, p.elem, count(p.count), !!p.nullable, !!p.bytes]
            case 'struct': return [k, name, p.dir, recName(p.record), !!p.nullable]
            case 'structArray': return [k, name, p.dir, recName(p.record), count(p.count), !!p.nullable]
            case 'structValue': return [k, name, recName(p.record)]
            default: return [k ?? 'x', name]
        }
    }
    const retSpec = (r) => {
        switch (r?.kind) {
            case 'void': return ['v']
            case 'scalar': return ['s']
            case 'cstr': return ['c']
            case 'callResult': return ['cr', r.record]
            case 'structValue': return ['tv', recName(r.record)]
            case 'structCopy': return ['tc', recName(r.record)]
            case 'bytes': return ['b']
            default: return ['v']
        }
    }
    const methodSpec = (m) => {
        const status = { generated: 0, manual: 1 }[m.status] ?? 2
        const row = [m.index, m.jsName, m.params.map(paramSpec), retSpec(m.ret), status]
        if (status === 2) row.push(m.reason ?? m.status)
        if (status === 1) row.push(m.flat)
        return row
    }

    const interfaces = model.interfaces.filter(i => !i.excluded)
    const lines = []
    lines.push(`// @generated by scripts/sdk/generate.mjs from steam_api.json (${model.sdkVersion}).`)
    lines.push('// Do not edit by hand.')
    lines.push("'use strict'")
    lines.push('')
    lines.push(`exports.sdkVersion = ${JSON.stringify(model.sdkVersion)}`)
    lines.push('')
    lines.push('// [accessor name, interface, pipe] in native accessor order')
    lines.push('exports.accessors = [')
    for (const i of interfaces) for (const a of i.accessors) lines.push(`    ${JSON.stringify([a.name, i.name, a.kind])},`)
    lines.push(']')
    lines.push('')
    lines.push('// interface -> [index, name, params, return, status(0 generated, 1 manual, 2 unavailable), reason | flat name]')
    lines.push('exports.interfaces = {')
    for (const i of interfaces) {
        lines.push(`    ${i.name}: [`)
        for (const m of i.methods) lines.push(`        ${JSON.stringify(methodSpec(m))},`)
        lines.push('    ],')
    }
    lines.push('}')
    lines.push('')
    lines.push('// record -> { fields: [name, kind, arg][], methods, ctor, callback }')
    lines.push('exports.records = {')
    for (const r of model.records.values()) {
        if (r.opaque) continue
        const fields = r.fields.map(f => {
            const k = f.kind
            switch (k.k) {
                case 'string': case 'bytes': return [f.name, k.k, k.len]
                case 'array': return [f.name, 'array', [k.of, k.len]]
                case 'struct': return [f.name, 'struct', recName(k.name)]
                case 'structArray': return [f.name, 'structArray', [recName(k.name), k.len]]
                default: return [f.name, k.k]
            }
        })
        const methods = r.methods.map(methodSpec)
        lines.push(`    ${JSON.stringify(r.name)}: { fields: ${JSON.stringify(fields)}, methods: ${JSON.stringify(methods)}, ctor: ${r.ctor ? r.ctor.index : null}, callback: ${r.callbackId ?? null} },`)
    }
    lines.push('}')
    lines.push('')
    lines.push('// [id, name, names of pointer fields copied natively, in order]')
    lines.push('exports.callbacks = [')
    for (const cb of model.callbacks) {
        if (cb.record.opaque) continue
        lines.push(`    ${JSON.stringify([cb.id, cb.name, cb.cstrFields.map(f => f.name)])},`)
    }
    lines.push(']')
    lines.push('')
    lines.push('exports.enums = {')
    for (const e of model.enums) {
        const entries = e.values.map(v => `${JSON.stringify(v.name)}: ${v.value}`)
        lines.push(`    ${e.name}: { ${entries.join(', ')} },`)
    }
    lines.push('}')
    lines.push('')
    lines.push('exports.constants = {')
    for (const c of model.consts) {
        const big = c.num === 'u64' || c.num === 'i64'
        let v = c.value
        if (big) {
            v = BigInt(v)
            if (c.num === 'u64' && v < 0n) v = BigInt.asUintN(64, v)
            v = `${v}n`
        } else if (typeof v === 'bigint') {
            // 32-bit values: keep the C type's signedness
            v = c.num?.startsWith('i') ? BigInt.asIntN(32, v) : BigInt.asUintN(32, v)
            v = String(v)
        }
        lines.push(`    ${c.name}: ${v},`)
    }
    lines.push('}')
    return lines.join('\n') + '\n'
}
